-- Run once in the Supabase SQL Editor. Safe to re-run.
--
-- Replaces the old flat `site_content` key/value table (8 fixed fields,
-- never actually wired into the public site) with a versioned content
-- system that covers every editable string and every editable card/list
-- across the whole site — see src/content/registry.js (individual text
-- fields) and src/content/collections.js (services, industries, why-us,
-- nav links, SEO titles, etc).
--
-- Shape: one row holds the WHOLE site's content as two JSON blobs —
--   text: { "Hero.1": "...", "Contact.2": "...", ... }
--   data: { "services": [ {...}, {...} ], "navLinks": [...], ... }
-- Editing one field only ever touches these two blobs; nothing here is
-- tied to a specific page's code, so new editable fields (added by future
-- code changes) show up automatically without a migration.

drop table if exists site_content;

-- The one row currently being edited in the admin panel. Autosaved on every
-- change so nobody loses work; NOT what the public site shows.
create table if not exists content_draft (
  id boolean primary key default true,
  text jsonb not null default '{}'::jsonb,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  updated_by uuid references admins(id) on delete set null,
  constraint content_draft_single_row check (id)
);

insert into content_draft (id) values (true) on conflict (id) do nothing;

-- Append-only history of published snapshots. The public site (and the
-- pre-build fetch step) always reads the row with the highest `version`.
create table if not exists content_published (
  version integer generated by default as identity primary key,
  text jsonb not null default '{}'::jsonb,
  data jsonb not null default '{}'::jsonb,
  published_at timestamptz not null default now(),
  published_by uuid references admins(id) on delete set null,
  note text
);

create index if not exists content_published_version_idx on content_published (version desc);

alter table content_draft enable row level security;
alter table content_published enable row level security;
